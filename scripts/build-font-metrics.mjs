/**
 * Glyph advance widths from public/fonts into a committed data module, so
 * measuring text needs no font parser at runtime. Run with `pnpm font-metrics`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { openSync } from "fontkit";

const families = {
  Inter: "inter",
  "Space Grotesk": "space-grotesk",
  "IBM Plex Sans": "ibm-plex-sans",
  "Playfair Display": "playfair-display",
  "JetBrains Mono": "jetbrains-mono",
};

const weights = [400, 700];

const ranges = [
  [0x20, 0x7e], // printable ASCII
  [0xa0, 0xff], // Latin-1 supplement, for accented names
];

/** Typography the model and the Brand Kit actually produce. */
const extras = "‘’‚“”„–—―…•·‹›€₹™←→↑↓✓✗≈≠≤≥∞";

const charset = [
  ...ranges.flatMap(([from, to]) =>
    Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i)),
  ),
  ...extras,
].join("");

function widthsFor(file) {
  const font = openSync(file);
  const em = font.unitsPerEm;

  const widths = [...charset].map((char) => {
    const [glyph] = font.layout(char).glyphs;
    return Math.round((glyph.advanceWidth / em) * 10000) / 10000;
  });

  // Unknown codepoints bill at the width of a lowercase n, the usual stand-in.
  const [n] = font.layout("n").glyphs;

  return { widths, fallback: Math.round((n.advanceWidth / em) * 10000) / 10000 };
}

const entries = Object.entries(families).map(([family, slug]) => {
  const perWeight = weights.map((weight) => {
    const file = path.join(process.cwd(), "public", "fonts", `${slug}-${weight}.ttf`);
    const { widths, fallback } = widthsFor(file);

    return `    ${weight}: { fallback: ${fallback}, widths: [${widths.join(",")}] },`;
  });

  return `  ${JSON.stringify(family)}: {\n${perWeight.join("\n")}\n  },`;
});

const source = `/**
 * Generated by scripts/build-font-metrics.mjs. Do not edit by hand.
 * Advance widths in em units, indexed by position in \`metricsCharset\`.
 */

export const metricsCharset = ${JSON.stringify(charset)};

export type MetricsWeight = 400 | 700;

export type FontMetrics = { fallback: number; widths: number[] };

export const fontMetrics: Record<string, Record<MetricsWeight, FontMetrics>> = {
${entries.join("\n")}
};
`;

const target = path.join(process.cwd(), "src", "templates", "font-metrics.ts");
writeFileSync(target, source);

const before = readFileSync(target, "utf8").length;
console.log(`wrote ${target} (${before} bytes, ${charset.length} glyphs per face)`);
